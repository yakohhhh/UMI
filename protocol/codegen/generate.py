#!/usr/bin/env python3
"""Generate the shared constants for every component from protocol/constants.toml.

Standard library only (Python >= 3.11), so it runs anywhere without a venv:

    python3 protocol/codegen/generate.py          # write the generated files
    python3 protocol/codegen/generate.py --check  # exit 1 if a generated file is stale (CI)
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "protocol" / "constants.toml"

C_HEADER = ROOT / "firmware" / "lib" / "umi_protocol" / "include" / "umi" / "protocol_gen.h"
PY_MODULE = ROOT / "protocol" / "python" / "src" / "umi_protocol" / "constants.py"
TS_MODULE = ROOT / "src" / "lib" / "generated" / "protocol.ts"

BANNER = "Generated by protocol/codegen/generate.py from protocol/constants.toml. Do not edit."

Scalar = bool | int | float | str


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def is_flag_enum(name: str) -> bool:
    return name.endswith("_flag")


def split(spec: dict) -> tuple[dict[str, dict[str, Scalar]], dict[str, dict[str, int]]]:
    enums = spec.get("enum", {})
    sections = {k: v for k, v in spec.items() if k != "enum"}
    for section, values in sections.items():
        for key, value in values.items():
            if not isinstance(value, (bool, int, float, str)):
                raise SystemExit(f"[{section}] {key}: only scalars are supported, got {type(value).__name__}")
    for name, members in enums.items():
        for key, value in members.items():
            if not isinstance(value, int) or isinstance(value, bool):
                raise SystemExit(f"[enum.{name}] {key}: enum values must be integers")
        if len(set(members.values())) != len(members):
            raise SystemExit(f"[enum.{name}]: duplicate values")
    return sections, enums


# ---------------------------------------------------------------- C


def c_literal(value: Scalar) -> str:
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return f"{value}" if value >= 0 else f"({value})"
    if isinstance(value, float):
        return f"{value!r}f"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_c(sections: dict[str, dict[str, Scalar]], enums: dict[str, dict[str, int]]) -> str:
    out = [f"/* {BANNER} */", "#ifndef UMI_PROTOCOL_GEN_H", "#define UMI_PROTOCOL_GEN_H", ""]
    for section, values in sections.items():
        out.append(f"/* [{section}] */")
        for key, value in values.items():
            out.append(f"#define UMI_{section.upper()}_{key.upper()} {c_literal(value)}")
        out.append("")
    for name, members in enums.items():
        out.append("typedef enum {")
        for key, value in members.items():
            out.append(f"    UMI_{name.upper()}_{key.upper()} = {value},")
        out.append(f"}} umi_{name}_t;")
        out.append("")
    out.append("#endif /* UMI_PROTOCOL_GEN_H */")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- Python


def render_py(sections: dict[str, dict[str, Scalar]], enums: dict[str, dict[str, int]]) -> str:
    out = [f'"""{BANNER}"""', "", "from enum import IntEnum, IntFlag", ""]
    for section, values in sections.items():
        out.append(f"# [{section}]")
        for key, value in values.items():
            out.append(f"{section.upper()}_{key.upper()} = {value!r}")
        out.append("")
    for name, members in enums.items():
        base = "IntFlag" if is_flag_enum(name) else "IntEnum"
        out.append("")
        out.append(f"class {pascal(name)}({base}):")
        for key, value in members.items():
            out.append(f"    {key.upper()} = {value}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- TypeScript


def ts_literal(value: Scalar) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return repr(value)


def render_ts(sections: dict[str, dict[str, Scalar]], enums: dict[str, dict[str, int]]) -> str:
    out = [f"// {BANNER}", ""]
    for section, values in sections.items():
        out.append(f"export const {section.upper()} = {{")
        for key, value in values.items():
            out.append(f"  {camel(key)}: {ts_literal(value)},")
        out.append("} as const;")
        out.append("")
    for name, members in enums.items():
        const = f"{name.upper()}_CODE"
        out.append(f"/** Wire codes for `{name}` (protocol/constants.toml). */")
        out.append(f"export const {const} = {{")
        for key, value in members.items():
            out.append(f"  {key}: {value},")
        out.append("} as const;")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


TARGETS: list[tuple[Path, Callable[[dict, dict], str]]] = [
    (C_HEADER, render_c),
    (PY_MODULE, render_py),
    (TS_MODULE, render_ts),
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if a generated file is missing or stale")
    args = parser.parse_args()

    with SOURCE.open("rb") as fh:
        sections, enums = split(tomllib.load(fh))

    stale: list[Path] = []
    for path, render in TARGETS:
        content = render(sections, enums)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        print("Run: python3 protocol/codegen/generate.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
